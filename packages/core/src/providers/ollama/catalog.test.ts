/**
 * Ollama response parsing, against recorded responses.
 *
 * The fixtures are the shapes Ollama actually returns, trimmed of model names
 * that would date the file. They are the contract: if `/api/tags` or
 * `/api/show` changes shape, these fail here rather than in a user's empty
 * Models tab.
 *
 * The malformed cases matter as much as the happy path. A response that cannot be
 * read has to raise rather than parse into an empty list, because "Ollama is
 * running with nothing installed" and "Ollama sent something unexpected" are
 * different things and the UI gives the user different advice for each.
 */

